/** A random line; `exclude` avoids showing the same one twice in a row. */
export function pickRoast(exclude?: string): string {
  const pool = exclude ? ROASTS.filter((r) => r !== exclude) : ROASTS;
  return pool[Math.floor(Math.random() * pool.length)];
}
